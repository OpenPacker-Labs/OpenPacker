import type {
  Digest,
  JsonValue,
  ResolutionProof,
  ResolutionSolution,
  ResolutionUniverse,
  SolveRequest,
} from '@openpacker/contracts';

export interface EmbeddedSolveInput {
  request: SolveRequest;
  universe: ResolutionUniverse;
}

export interface EmbeddedSolveOutput {
  normalizedRequest: SolveRequest;
  requestDigest: Digest;
  universeDigest: Digest;
  selected: ResolutionUniverse['packages'];
  solution: ResolutionSolution;
  proof: ResolutionProof;
  explanation: JsonValue;
}

export interface ProofCheckResult {
  valid: boolean;
  diagnostics: string[];
}

export interface OracleResult {
  selectedNodeIds: string[];
  assignmentsChecked: number;
}

/** The stable, engine-neutral exports generated by wasm-bindgen. */
export interface EmbeddedBindings {
  solve_json(input: string): string;
  check_json(input: string, output: string): string;
  validate_universe_json(input: string): void;
  brute_force_oracle_json(input: string): string;
  canonicalize_json(input: string): string;
  digest_json(input: string): string;
  version_satisfies(version: string, vers: string): boolean;
  normalize_purl(value: string): string;
  parse_vers_json(value: string): string;
  verify_sha256(bytes: Uint8Array, expected: string): boolean;
  verify_receipt_digest(receipt: string, expected: string): boolean;
}

type LoadableBindings = EmbeddedBindings & {
  default?: () => Promise<void> | void;
};
export type EmbeddedImporter = () => Promise<LoadableBindings>;

function encode(value: unknown): string {
  const encoded = JSON.stringify(value);
  if (encoded === undefined)
    throw new TypeError('Embedded PREX inputs must be JSON values');
  return encoded;
}

function decode<T>(value: string): T {
  // SAFETY: The surrounding boundary establishes the asserted domain contract.
  return JSON.parse(value) as T;
}

export class EmbeddedResolver {
  constructor(private readonly bindings: EmbeddedBindings) {}

  solve(input: EmbeddedSolveInput): EmbeddedSolveOutput {
    return decode(this.bindings.solve_json(encode(input)));
  }

  check(
    input: EmbeddedSolveInput,
    output: EmbeddedSolveOutput,
  ): ProofCheckResult {
    return decode(this.bindings.check_json(encode(input), encode(output)));
  }

  validateUniverse(universe: ResolutionUniverse): void {
    this.bindings.validate_universe_json(encode(universe));
  }

  bruteForceOracle(input: EmbeddedSolveInput): OracleResult {
    return decode(this.bindings.brute_force_oracle_json(encode(input)));
  }

  canonicalize(value: JsonValue): string {
    return this.bindings.canonicalize_json(encode(value));
  }

  digest(value: JsonValue): Digest {
    return decode(this.bindings.digest_json(encode(value)));
  }

  versionSatisfies(version: string, vers: string): boolean {
    return this.bindings.version_satisfies(version, vers);
  }

  normalizePurl(value: string): string {
    return this.bindings.normalize_purl(value);
  }

  parseVers(value: string): import('@openpacker/contracts').VersionConstraint {
    return decode(this.bindings.parse_vers_json(value));
  }

  verifyArtifactDigest(bytes: Uint8Array, expected: string): boolean {
    return this.bindings.verify_sha256(bytes, expected);
  }

  verifyReceiptDigest(receipt: JsonValue, expected: string): boolean {
    return this.bindings.verify_receipt_digest(encode(receipt), expected);
  }
}

/** Wrap a native or WASM binding without changing PREX semantics. */
export function createEmbeddedResolver(
  bindings: EmbeddedBindings,
): EmbeddedResolver {
  return new EmbeddedResolver(bindings);
}

/**
 * Load the wasm-bindgen module asynchronously in Node or a modern browser.
 * Build tooling copies `openpacker_wasm.js` and its `.wasm` beside this entry.
 */
export async function loadEmbeddedResolver(
  importer?: EmbeddedImporter,
): Promise<EmbeddedResolver> {
  const load =
    importer ??
    (async () => {
      const specifier = './openpacker_wasm.js';
      // SAFETY: The surrounding boundary establishes the asserted domain contract.
      return (await import(specifier)) as LoadableBindings;
    });
  const module = await load();
  await module.default?.();
  return createEmbeddedResolver(module);
}
